// Real UI, HTTP owners and disk, isolated by the Python caller. Headless input only.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {chromium} = require('playwright');
const {test} = require('node:test');

test('CHECKPOINT: document round trip and inspector owner width', async () => {
  const cache = process.env.PLAYWRIGHT_BROWSERS_PATH || path.join(os.userInfo().homedir, 'AppData/Local/ms-playwright');
  const shell = fs.readdirSync(cache).filter(name => /^chromium_headless_shell-\d+$/.test(name)).sort((a,b) => Number(b.split('-').at(-1))-Number(a.split('-').at(-1)))[0];
  const full = fs.readdirSync(cache).filter(name => /^chromium-\d+$/.test(name)).sort((a,b) => Number(b.split('-').at(-1))-Number(a.split('-').at(-1)))[0];
  const browser = await chromium.launch({headless:true, executablePath: process.env.CHROME_PATH || ((shell || full) ? path.join(cache, shell || full, shell ? 'chrome-headless-shell-win64/chrome-headless-shell.exe' : 'chrome-win64/chrome.exe') : undefined)});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    page.setDefaultTimeout(10000);
    const origin = new URL(process.env.CHECKPOINT_URL).origin;
    await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort('internetdisconnected'));
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.env.CHECKPOINT_URL, {waitUntil:'domcontentloaded'});
    await page.waitForFunction(() => window.ArchHubAPI && !document.getElementById('studio-boot') && document.querySelector('[data-home-ready]'));
    const task = await page.evaluate(async () => {
      const api = window.ArchHubAPI;
      await api.ready;
      const task = await api.createTask('Checkpoint browser task');
      await api.openTaskGraph(task.taskId);
      await api.setTaskSession(task.taskId, {plan:['Original plan'], nodes:[{id:'original',type:'note',title:'Original',params:{text:'before'}}]});
      await api.openSession(task.path);
      await api.saveSession();
      return task;
    });
    await page.getByRole('navigation', {name:'Main navigation'}).getByRole('button', {name:'Workshop',exact:true}).click();
    await page.getByRole('textbox', {name:'Task title',exact:true}).waitFor();
    const original = await page.evaluate(() => window.ArchHubAPI.getSessionDocument());
    await page.locator('details').filter({has:page.locator('summary', {hasText:'Checkpoints'})}).locator('summary').click();
    await page.getByRole('button', {name:'Save checkpoint',exact:true}).click();
    await page.waitForFunction(id => window.ArchHubAPI.getSnapshot().tasks.find(t=>t.id===id)?.checkpoints?.length === 1, task.taskId);
    const saved = await page.evaluate(id => window.ArchHubAPI.getSnapshot().tasks.find(t=>t.id===id).checkpoints[0], task.taskId);
    assert.ok(saved.title && saved.at);
    await page.getByLabel('Checkpoints', {exact:true}).selectOption(saved.id);
    assert.equal(await page.getByLabel('Checkpoints', {exact:true}).locator('option:checked').innerText(), saved.title);
    assert.ok(saved.title.includes(saved.at));
    assert.match(await page.getByLabel('Checkpoints', {exact:true}).inputValue(), new RegExp(saved.id));
    await page.evaluate(async () => {await window.ArchHubAPI.moveNodes({original:{x:120,y:240}});});
    assert.notDeepEqual((await page.evaluate(() => window.ArchHubAPI.getSessionDocument())).nodes, original.nodes);
    await page.getByRole('button', {name:'Restore',exact:true}).click();
    await page.waitForFunction(nodes => JSON.stringify(window.ArchHubAPI.getSessionDocument().nodes) === JSON.stringify(nodes), original.nodes);
    const content = doc => Object.fromEntries(Object.entries(doc).filter(([key]) => key !== 'properties'));
    assert.deepEqual(content(await page.evaluate(() => window.ArchHubAPI.getSessionDocument())), content(original));
    await page.reload({waitUntil:'domcontentloaded'});
    await page.waitForFunction(id => window.ArchHubAPI?.getSnapshot().tasks.some(t=>t.id===id&&t.checkpoints?.length===1), task.taskId);
    await page.getByRole('navigation', {name:'Main navigation'}).getByRole('button', {name:'Home',exact:true}).click();
    await page.locator('.dx-task').filter({hasText:'Checkpoint browser task'}).click();
    await page.getByRole('navigation', {name:'Main navigation'}).getByRole('button', {name:'Workshop',exact:true}).click();
    await page.getByRole('textbox', {name:'Task title',exact:true}).waitFor();
    assert.deepEqual(content(await page.evaluate(() => window.ArchHubAPI.getSessionDocument())), content(original));
    console.log('PASS checkpoint: UI save -> time/label listed -> edit -> UI restore -> document equal -> reload retains checkpoint and document');
    if (process.env.CHECKPOINT_WIDTH !== '1') return;
    const params = page.locator('#params');
    const handle = await page.getByRole('separator', {name:'Resize the Properties pane'}).boundingBox();
    const before = await params.boundingBox();
    const groupWidth = await page.locator('#home-context').evaluate(element => element.offsetWidth);
    let releaseWidthSave;
    const widthSave = new Promise(resolve => { releaseWidthSave = resolve; });
    await page.route('**/api/universal/settings-action', async route => {
      const body = route.request().postDataJSON();
      if (body.function === 'setAppearance' && body.args[0] === 'Appearance.Inspector width') await widthSave;
      await route.continue();
    });
    const x = handle.x + handle.width/2, y = handle.y + handle.height/2;
    const input = await page.context().newCDPSession(page);
    await input.send('Input.dispatchMouseEvent', {type:'mouseMoved',x,y});
    await input.send('Input.dispatchMouseEvent', {type:'mousePressed',x,y,button:'left',buttons:1,clickCount:1});
    await input.send('Input.dispatchMouseEvent', {type:'mouseMoved',x:x-(375-before.width),y,button:'left',buttons:1});
    await input.send('Input.dispatchMouseEvent', {type:'mouseReleased',x:x-(375-before.width),y,button:'left',buttons:0,clickCount:1});
    await input.detach();
    await page.getByRole('status', {name:'', exact:true}).filter({hasText:/^Saving$/}).waitFor();
    assert.equal(await page.getByRole('status').filter({hasText:/^Saving$/}).evaluate(element => window.getComputedStyle(element).pointerEvents), 'none');
    assert.equal(await page.locator('#home-context').evaluate(element => element.offsetWidth), groupWidth);
    assert.equal(await params.evaluate(element => element.offsetWidth), 375);
    releaseWidthSave();
    await page.waitForFunction(() => window.ArchHubAPI.getSnapshot().settings.find(row=>row.id==='Appearance.Inspector width').value === 375);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const after = await params.boundingBox();
    const live = await params.evaluate(element => element.offsetWidth);
    const stored = await page.evaluate(() => window.ArchHubAPI.getSnapshot().settings.find(row=>row.id==='Appearance.Inspector width').value);
    assert.equal(live, 375, JSON.stringify({live,bounds:after.width,stored}));
    assert.ok(Math.abs(after.width-live) < 0.5, JSON.stringify({live,bounds:after.width}));
    await page.reload({waitUntil:'domcontentloaded'});
    await page.waitForFunction(() => window.ArchHubAPI && !document.getElementById('studio-boot') && document.querySelector('[data-home-ready]'));
    await page.waitForFunction(() => window.ArchHubAPI.getSnapshot().settings.find(row=>row.id==='Appearance.Inspector width')?.value === 375 && document.getElementById('params')?.offsetWidth === 375);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const reopened = await params.boundingBox();
    assert.equal(await params.evaluate(element => element.offsetWidth), 375);
    assert.ok(Math.abs(reopened.width-375) < 0.5, JSON.stringify({reopened:reopened.width}));
    console.log('PASS pane: ' + JSON.stringify({before:before.width,live,stored,reopened:await params.evaluate(element => element.offsetWidth),bounds:after.width}));
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
