"""Generate the source reference from the application's actual node catalogue."""
from __future__ import annotations

import argparse
import inspect
import json
from pathlib import Path

from nodelang.application_server import ApplicationServer
from nodelang.cell_model_execution import read_model_delegation
from nodelang.clean_host_catalogue_source import HOST_OPERATION_RECORDS
from nodelang.clean_revit_adapter import invoke
from nodelang.http_server import create_http_server
from nodelang.library_engines import STEM_RUN_ENGINES, library_catalogue
from nodelang.pipeline_engines import PIPELINE_ENGINES
from nodelang.stem_graph_evaluation import run_stem_operation
from nodelang.universal_cell import CellStore, open_read_only_cell_journal


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "CATALOGUE.md"


def _text(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def _source(function):
    path = Path(inspect.getsourcefile(function)).resolve().relative_to(ROOT)
    line = inspect.getsourcelines(function)[1]
    return f"[{function.__name__}](../{path.as_posix()}#L{line})"


def _implementation(engine):
    function = PIPELINE_ENGINES.get(engine)
    if function is None:
        if engine not in STEM_RUN_ENGINES:
            return "Unavailable"
        function = run_stem_operation
    return _source(function)


def render():
    rows = [
        "# Application catalogue reference",
        "",
        "Generated by `python -m tools.generate_catalogue_docs` from "
        "`library_catalogue()`, `PIPELINE_ENGINES` and `HOST_OPERATION_RECORDS`. "
        "Regenerate after changing their source; `--check` detects drift.",
        "",
        "This describes this source tree. It makes no installed or release claim. "
        "Hidden rows preserve existing graph placements.",
        "",
        "## Shared runtime owners",
        "",
        "| Job | Owner |",
        "|---|---|",
    ]
    for job, owner in (
        ("Installed application HTTP routes", ApplicationServer),
        ("HTTP transport construction", create_http_server),
        ("Universal graph journal", CellStore),
        ("Read-only graph observers", open_read_only_cell_journal),
        ("Revit operations", invoke),
        ("Model delegation records", read_model_delegation),
    ):
        rows.append(f"| {job} | {_source(owner)} |")
    rows += [
        "",
        "## Node catalogue",
        "",
        "| Group | Node | Engine | Defaults | Implementation | Visibility |",
        "|---|---|---|---|---|---|",
    ]
    for group in library_catalogue():
        for item in group["items"]:
            values = (
                group["cat"], item["id"], item["engine"],
                json.dumps(item["params"], sort_keys=True, ensure_ascii=True),
                _implementation(item["engine"]),
                "hidden" if item.get("hidden") else "visible",
            )
            rows.append("| " + " | ".join(map(_text, values)) + " |")
    rows += [
        "", "## Host operation catalogue", "",
        "Operations and defaults below come directly from the source used to seed "
        "the graph. The Revit operations execute through "
        "[the Revit adapter](../nodelang/clean_revit_adapter.py).",
        "", "| Host | Operation | Kind | Inputs and defaults |",
        "|---|---|---|---|",
    ]
    for operation in HOST_OPERATION_RECORDS:
        defaults = {item["id"]: item["default"] for item in operation["inputs"]}
        values = (
            operation["host"], operation["op_id"], operation["kind"],
            json.dumps(defaults, sort_keys=True, ensure_ascii=True),
        )
        rows.append("| " + " | ".join(map(_text, values)) + " |")
    return "\n".join(rows) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            parser.exit(1, "Catalogue reference is stale; regenerate it.\n")
        print("CATALOGUE DOCS PASS")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
        print("Generated docs/CATALOGUE.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
